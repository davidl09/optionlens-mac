// The Windows update helper: a PowerShell script, generated from one fixed template, that runs after
// OptionLens has quit. It waits for the app's process to exit, runs the NSIS installer silently
// (`/S --updated`: per-user, no prompts; the installer replaces the previous version in place), and starts
// OptionLens again. When the installer fails it runs `fallback` (the previous version's installer) to put
// that version back. The only inputs are a PID and absolute paths, each single-quoted for PowerShell, so
// nothing downloaded is executed as a script.
//
// The installer is started from the helper's temp folder. Files that OptionLens writes itself carry no
// Mark-of-the-Web, so SmartScreen does not prompt for them (only browser downloads are marked).
import { win32 } from "node:path";

export interface WindowsHelperPlan {
  pid: number;
  /** The installer to run silently. */
  installer: string;
  /** The previous version's installer, run if `installer` fails; null: none. */
  fallback: string | null;
  /** OptionLens.exe, started again at the end. */
  app: string;
  logFile: string;
  /** The helper's own temp folder, removed at the end. */
  workDir: string;
}

/** Single-quotes `s` for PowerShell: ' and its typographic variants (which PowerShell also accepts) are doubled. */
export function psQuote(s: string): string {
  return `'${s.replace(/['\u2018\u2019\u201a\u201b]/g, "$&$&")}'`;
}

function checkPath(name: string, p: string): string {
  if (!win32.isAbsolute(p) || !/^([A-Za-z]:\\|\\\\)/.test(p) || /[\0-\x1f]/.test(p)) {
    throw new Error(`update helper: ${name} must be an absolute Windows path without control characters`);
  }
  return psQuote(p);
}

export function windowsHelperScript(p: WindowsHelperPlan): string {
  if (!Number.isInteger(p.pid) || p.pid <= 4) throw new Error("update helper: invalid pid");
  const vars = [
    `$AppPid = ${p.pid}`,
    `$Installer = ${checkPath("installer", p.installer)}`,
    `$Fallback = ${p.fallback ? checkPath("fallback", p.fallback) : "''"}`,
    `$App = ${checkPath("app", p.app)}`,
    `$Log = ${checkPath("log file", p.logFile)}`,
    `$WorkDir = ${checkPath("work dir", p.workDir)}`,
  ];
  return `# Generated by OptionLens (electron/main/updater/windows-helper.ts): installs the update after the app quits.
$ErrorActionPreference = 'Continue'
${vars.join("\r\n")}
function Write-Log([string]$Message) {
  $line = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ') + ' updater: ' + $Message
  Add-Content -LiteralPath $Log -Value $line -Encoding UTF8
}
function Invoke-Installer([string]$Setup) {
  Write-Log "running $Setup /S"
  $p = Start-Process -FilePath $Setup -ArgumentList '/S', '--updated' -PassThru -WindowStyle Hidden
  $null = $p.Handle
  $p.WaitForExit()
  return $p.ExitCode
}
function Exit-Helper([int]$Code) {
  if (Test-Path -LiteralPath $App -PathType Leaf) { Start-Process -FilePath $App } else { Write-Log "$App is missing; reinstall OptionLens" }
  Remove-Item -LiteralPath $WorkDir -Recurse -Force -ErrorAction SilentlyContinue
  exit $Code
}

Write-Log "waiting for OptionLens (pid $AppPid) to quit"
$deadline = (Get-Date).AddSeconds(120)
while (Get-Process -Id $AppPid -ErrorAction SilentlyContinue) {
  if ((Get-Date) -gt $deadline) {
    Write-Log 'OptionLens did not quit within 120 s; nothing changed'
    Remove-Item -LiteralPath $WorkDir -Recurse -Force -ErrorAction SilentlyContinue
    exit 1
  }
  Start-Sleep -Milliseconds 500
}
if (-not (Test-Path -LiteralPath $Installer -PathType Leaf)) { Write-Log "$Installer is missing; nothing changed"; Exit-Helper 1 }
$code = Invoke-Installer $Installer
if ($code -eq 0) { Write-Log "installed $Installer"; Exit-Helper 0 }
Write-Log "the installer failed (exit code $code)"
if ($Fallback -and (Test-Path -LiteralPath $Fallback -PathType Leaf)) {
  $code = Invoke-Installer $Fallback
  Write-Log "restored the previous version (exit code $code)"
}
Exit-Helper 1
`.replace(/\r?\n/g, "\r\n");
}

export interface WindowsHelperDeps {
  makeTempDir(): Promise<string>;
  copyFile(from: string, to: string): Promise<void>;
  writeFile(path: string, content: string): Promise<void>;
  spawnDetached(file: string, args: string[]): void;
  /** Absolute path of Windows PowerShell 5.1 (%SystemRoot%\System32\WindowsPowerShell\v1.0\powershell.exe). */
  powershell: string;
}

export const POWERSHELL_ARGS = ["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-WindowStyle", "Hidden", "-File"] as const;

/** Copies the installer into a new temp folder, writes the script there and starts it detached. */
export async function launchWindowsHelper(plan: Omit<WindowsHelperPlan, "workDir">, deps: WindowsHelperDeps): Promise<void> {
  const workDir = await deps.makeTempDir();
  const installer = win32.join(workDir, win32.basename(plan.installer));
  await deps.copyFile(plan.installer, installer);
  const file = win32.join(workDir, "update.ps1");
  // UTF-8 with a BOM: Windows PowerShell 5.1 reads a script without one in the ANSI code page, which would
  // garble non-ASCII characters in paths (e.g. the user name in C:\Users\…).
  await deps.writeFile(file, `\ufeff${windowsHelperScript({ ...plan, installer, workDir })}`);
  deps.spawnDetached(deps.powershell, [...POWERSHELL_ARGS, file]);
}
