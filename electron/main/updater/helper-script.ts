// The detached helper that swaps the app bundle after OptionLens has quit (a running app cannot replace
// itself). It is generated here from one fixed template; the only inputs are a PID and absolute paths,
// each single-quoted for the shell, so nothing downloaded is ever executed as a script.
//
// It waits for the app to exit, moves the current bundle to `archive` (a backup, or a discard folder on
// rollback), moves `source` into its place, prunes old backups, opens the app and logs to `logFile`. When a
// move fails it puts the previous bundle back and opens that instead.
import { isAbsolute } from "node:path";

export interface SwapPlan {
  pid: number;
  /** The installed bundle, e.g. /Applications/OptionLens.app. */
  target: string;
  /** The bundle that replaces it (the staged update, or the backup on rollback). */
  source: string;
  /** Where the current bundle goes. */
  archive: string;
  /** Folder of OptionLens-<version>.app backups to prune to the newest `keep`, or null. */
  prune: { dir: string; keep: number } | null;
  logFile: string;
  /** The helper's own temp folder, removed at the end. */
  workDir: string;
  /** The program that relaunches the app (/usr/bin/open; tests use a stand-in). */
  open: string;
}

/** Single-quotes `s` for bash ('…' with each ' written as '\''). */
export function shQuote(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

function checkPath(name: string, p: string): string {
  if (!isAbsolute(p) || /[\0\n\r]/.test(p)) throw new Error(`helper script: ${name} must be an absolute path without control characters`);
  return shQuote(p);
}

export function helperScript(p: SwapPlan): string {
  if (!Number.isInteger(p.pid) || p.pid <= 1) throw new Error("helper script: invalid pid");
  if (p.prune && !(Number.isInteger(p.prune.keep) && p.prune.keep >= 1)) throw new Error("helper script: invalid backup count");
  const vars = [
    `PID=${p.pid}`,
    `TARGET=${checkPath("target", p.target)}`,
    `SOURCE=${checkPath("source", p.source)}`,
    `ARCHIVE=${checkPath("archive", p.archive)}`,
    `PRUNE_DIR=${p.prune ? checkPath("prune dir", p.prune.dir) : "''"}`,
    `KEEP=${p.prune?.keep ?? 0}`,
    `LOG=${checkPath("log file", p.logFile)}`,
    `WORKDIR=${checkPath("work dir", p.workDir)}`,
    `OPEN=${checkPath("open", p.open)}`,
  ];
  return `#!/bin/bash
# Generated by OptionLens (electron/main/updater/helper-script.ts): replaces the app bundle after it quits.
set -u
${vars.join("\n")}
exec >>"$LOG" 2>&1
log() { printf '%s updater: %s\\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"; }
finish() { "$OPEN" "$TARGET" || log "could not open $TARGET"; rm -rf "$WORKDIR"; exit "$1"; }

log "waiting for OptionLens (pid $PID) to quit"
i=0
while kill -0 "$PID" 2>/dev/null; do
  i=$((i + 1))
  if [ "$i" -gt 240 ]; then log "OptionLens did not quit within 120 s; nothing changed"; rm -rf "$WORKDIR"; exit 1; fi
  sleep 0.5
done
if [ ! -d "$SOURCE" ]; then log "$SOURCE is missing; nothing changed"; finish 1; fi
mkdir -p "$(dirname "$ARCHIVE")"
rm -rf "$ARCHIVE"
if ! mv "$TARGET" "$ARCHIVE"; then log "could not move $TARGET aside; nothing changed"; finish 1; fi
touch "$ARCHIVE"
if ! mv "$SOURCE" "$TARGET"; then
  log "could not move $SOURCE into place; restoring the previous app"
  mv "$ARCHIVE" "$TARGET" || log "could not restore $TARGET from $ARCHIVE"
  finish 1
fi
log "replaced $TARGET (previous app: $ARCHIVE)"
if [ -n "$PRUNE_DIR" ]; then
  shopt -s nullglob
  backups=("$PRUNE_DIR"/OptionLens-*.app)
  if [ "\${#backups[@]}" -gt "$KEEP" ]; then
    # Newest first by modification time (each backup is touched when made); names are OptionLens-<version>.app.
    ls -1dt "\${backups[@]}" | tail -n +"$((KEEP + 1))" | while IFS= read -r old; do log "removing old backup $old"; rm -rf "$old"; done
  fi
fi
finish 0
`;
}
